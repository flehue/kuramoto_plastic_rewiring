def run_kuramoto_model(frequencies, K, T, dt, plasticity_function = None, normalization_function = None):
    N = len(frequencies)
    # Initialize the phases and frequencies of each unit
    phases = np.random.uniform(0, 2*np.pi, size=(N, 1))
    # Initialize the array to store the phases at each time step
    phases_t = np.zeros((N, int(T/dt)))
    # Initialize the array to store the K values at each time step
    if plasticity_function is not None:
        K_t = np.zeros((N, N, int(T/dt)))
        K_t[:,:,0] = K
    else:
        K_t = K

    # store initial vlaues
    phases_t[:, 0]  =phases.flatten()

    # Loop through the simulation time
    for t in range(1,int(T/dt)):
        # Compute the phase differences between all pairs of units
        phase_diffs = phases - phases.T
        # Compute the sinusoids of the phase differences
        sin_diffs = np.sin(phase_diffs.T)*K
        # Compute the sum of the sinusoids of the phase differences
        sin_sum = np.sum(sin_diffs, axis=1)
        # Update the phases of each unit
        phases = phases + dt*(frequencies + sin_sum).reshape(N,1)
        # wrap phase values
        phases %= 2 * np.pi
        # Store the phases at this time step
        phases_t[:, t]  =phases.flatten()

        # Update K values using the provided plasticity function
        if plasticity_function is not None:
            K = plasticity_function(K, phases)
            #K = hebbian_plasticity(K, groups, phases, post_group=0, pre_group=0, plasticity_rate=0.001, sharpness=2)


        # normalize K values using the provided normalization function
        if normalization_function is not None:
            K = normalization_function(K, phases)
            #K = normalize_all_K(K, groups, K_ee, K_ei, K_ie, K_ii)

            # store K values
            K_t[:,:,t] = K

    return phases_t, K_t

def hebbian_plasticity_cos(K, phases, groups, post_group, pre_group, plasticity_rate=0.001):
    post_mask = (groups == post_group)
    pre_mask = (groups == pre_group)

    phase_diff = phases[post_mask, :] - phases[pre_mask, :].T
    phase_diff %= 2 * np.pi
    phase_diff = np.minimum(phase_diff, 2 * np.pi - phase_diff)

    #gain = np.exp(-sharpness * phase_diff)  # Exponential gain function with sharpness control
    gain = (np.cos(phase_diff) + 1) / 2
    np.fill_diagonal(gain, 0)

    K[np.ix_(post_mask, pre_mask)] += plasticity_rate * gain


    return K

def hebbian_plasticity_exp(K, phases, groups, post_group, pre_group, plasticity_rate=0.001, sharpness=2):
    post_mask = (groups == post_group)
    pre_mask = (groups == pre_group)

    phase_diff = phases[post_mask, :] - phases[pre_mask, :].T
    phase_diff %= 2 * np.pi
    phase_diff = np.minimum(phase_diff, 2 * np.pi - phase_diff)

    gain = np.exp(-sharpness * phase_diff)  # Exponential gain function with sharpness control
    np.fill_diagonal(gain, 0)

    K[np.ix_(post_mask, pre_mask)] += plasticity_rate * gain


    return K

def hebbian_plasticity_norm(K, phases, groups, post_group, pre_group, plasticity_rate=0.001, sharpness=2):
    post_mask = (groups == post_group)
    pre_mask = (groups == pre_group)

    phase_diff = phases[post_mask, :] - phases[pre_mask, :].T
    phase_diff = np.angle(np.exp(1j * phase_diff))  # Maps phase_diff into the range [-np.pi, np.pi]

    gain = norm.pdf(phase_diff, loc=0, scale=sharpness)  # Normal distribution with mean 0 and std sharpness
    tmp = np.append(gain,0) # scaling gain between 0 - 1
    tmp = tmp / np.max(tmp)
    gain = tmp[:-1]

    np.fill_diagonal(gain, 0)

    K[np.ix_(post_mask, pre_mask)] += plasticity_rate * gain


    return K

