def kuramoto_model_3_iwave(N, w_e_mean, w_e_std, w_i_mean, w_i_std, K_ee, K_ei, K_ie, K_ii, wFreq, iwAmp, T, dt, group_proportions=[0.5, 0.5]):

    # Divide the units into Excitatory and Inhibitory groups
    N_exc = int(group_proportions[0]*N)
    N_inh = int(group_proportions[1]*N)
    groups = np.concatenate([np.zeros(N_exc), np.ones(N_inh)])
    np.random.shuffle(groups)

    # Initialize the phases and frequencies of each unit
    phases = np.random.uniform(0, 2*np.pi, size=(N, 1))
    frequencies = np.random.normal(w_e_mean, w_e_std, size=N)
    frequencies[groups == 1] = np.random.normal(w_i_mean, w_i_std, size=N_inh)

    # Initialize the array to store the phases at each time step
    phases_t = np.zeros((N, int(T/dt)))

    # Pre-compute the interaction strengths for each pair of units
    K = np.zeros((N, N))
    W = np.zeros((N, N)) # window for wave
    for i in range(N):
        for j in range(N):
            if groups[i] == 0 and groups[j] == 0:
                K[i, j] = K_ee/N_exc
            elif groups[i] == 1 and groups[j] == 0:
                K[i, j] = K_ei/N_exc
            elif groups[i] == 0 and groups[j] == 1:
                K[i, j] = K_ie/N_inh
                W[i, j] = 1
            elif groups[i] == 1 and groups[j] == 1:
                K[i, j] = K_ii/N_inh
                W[i, j] = 1

    # generate wave
    t = np.arange(0, T, dt)
    iwave_t = iwAmp*(np.sin(2*np.pi*wFreq*t)+1)/2

    # Exclude self-connection
    for i in range(N):
        K[i, i] = 0

    # Loop through the simulation time
    for t in range(int(T/dt)):
        # Compute the phase differences between all pairs of units
        phase_diffs = phases - phases.T
        # Compute the sinusoids of the phase differences
        sin_diffs = np.sin(phase_diffs.T)*K*(np.ones((N,N)) - W*iwave_t[t])
        # Compute the sum of the sinusoids of the phase differences
        sin_sum = np.sum(sin_diffs, axis=1)
        # Update the phases of each unit
        phases = phases + dt*(frequencies + sin_sum).reshape(N,1)
        # Store the phases at this time step
        phases_t[:, t]  =phases.flatten()

    return phases_t, frequencies, groups, iwave_t, K

