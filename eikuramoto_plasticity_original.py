def normalize_K_values(K, groups, target_K, post_group, pre_group):
    N_post = int(np.sum(groups == post_group))
    N_pre = int(np.sum(groups == pre_group))

    post_mask = (groups == post_group)
    pre_mask = (groups == pre_group)

    K_sum = K[np.ix_(post_mask, pre_mask)].sum(axis=1)
    K[np.ix_(post_mask, pre_mask)] *= (target_K / N_pre) / K_sum[:, np.newaxis]
    np.fill_diagonal(K, 0)

    return K

def normalize_K_values_norm(K, groups, target_mean, target_std, post_group, pre_group, modulation_rate=1.0):
    post_mask = (groups == post_group)
    pre_mask = (groups == pre_group)

    K_post_pre = K[np.ix_(post_mask, pre_mask)]
    np.fill_diagonal(K_post_pre, np.nan)

    K_mean = np.nanmean(K_post_pre, axis=1, keepdims=True)
    K_std = np.nanstd(K_post_pre, axis=1, keepdims=True)

    K_scaled = (K_post_pre - K_mean) * (target_std / K_std) + target_mean

    K_updated = K_post_pre + modulation_rate * (K_scaled - K_post_pre)

    K[np.ix_(post_mask, pre_mask)] = K_updated
    np.fill_diagonal(K, 0)

    return K

def normalize_K_values_mean(K, groups, target_mean, post_group, pre_group, modulation_rate=1.0):
    post_mask = (groups == post_group)
    pre_mask = (groups == pre_group)

    K_post_pre = K[np.ix_(post_mask, pre_mask)]
    np.fill_diagonal(K_post_pre, np.nan)

    K_scaled = (K_post_pre - target_mean)

    K_updated = K_post_pre + modulation_rate * (target_mean - K_post_pre)

    K[np.ix_(post_mask, pre_mask)] = K_updated
    np.fill_diagonal(K, 0)

    return K

