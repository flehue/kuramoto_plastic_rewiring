def d_theta_interaction (dθ, sigma, mu, sharpness, rl_hebb, rl_homeo):
  c = rl_hebb*(1-rl_homeo)/rl_homeo
  k = sharpness
  μ = c*(1-np.exp(-k*np.pi))/(k*np.pi)
  σ = np.sqrt(c**2*(1-np.exp(-2*k*np.pi))/(2*k*np.pi) - μ**2)

  j   = c*np.exp(-k*np.abs(dθ))
  jz = (j - μ) / σ
  return -2*(sigma * jz + mu + c* np.exp(-k*np.abs(dθ))) * np.sin(dθ)

