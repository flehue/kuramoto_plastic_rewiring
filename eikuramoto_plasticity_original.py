def plot_phases(phases_t, groups, frequencies, dt, sleep_time=0.5):

    # N of each group
    Ne = len(groups[groups == 0])
    Ni = len(groups[groups == 1])

    # Initialize the colors for each unit
    colors = []
    for i in range(phases_t.shape[0]):
        f_grp = frequencies[groups == groups[i]]
        max_f = np.max(f_grp)
        min_f = np.min(f_grp)
        base_f = (max_f - min_f)
        if groups[i] == 0:
            color = plt.cm.spring((frequencies[i]-min_f)/base_f)
        else:
            color = plt.cm.winter((frequencies[i]-min_f)/base_f)
        colors.append(color)

    # Loop through the simulation time
    for t in range(phases_t.shape[1]):

        Re = np.sum(np.exp(1j*phases_t[groups == 0, t]), axis=0) / Ne
        Ri = np.sum(np.exp(1j*phases_t[groups == 1, t]), axis=0) / Ni

        clear_output(wait=True)
        fig = plt.figure()
        ax = fig.add_subplot(projection='polar')
        ax.scatter(phases_t[:, t], -(groups - 2), c=colors)
        ax.plot([np.angle(Re), np.angle(Re)], [0, np.abs(Re)], 'r')
        ax.plot([np.angle(Ri), np.angle(Ri)], [0, np.abs(Ri)], 'b')
        ax.set_title(f"t = {t*dt:.2f}")
        ax.axes.yaxis.set_ticks([1,2])
        ax.axes.yaxis.set_ticklabels([])
        plt.show()

        time.sleep(sleep_time)

def init_EIkuramoto_model(N, w_e_mean, w_e_std, w_i_mean, w_i_std, group_proportions=[0.5, 0.5]):
    # Divide the units into Excitatory and Inhibitory groups
    N_exc = int(group_proportions[0]*N)
    N_inh = int(group_proportions[1]*N)
    groups = np.concatenate([np.zeros(N_exc), np.ones(N_inh)])
    np.random.shuffle(groups)

    frequencies = np.random.normal(w_e_mean, w_e_std, size=N)
    frequencies[groups == 1] = np.random.normal(w_i_mean, w_i_std, size=N_inh)

    return frequencies, groups

def generate_K_matrix_norm(groups, K_ee_mean, K_ee_std, K_ei_mean, K_ei_std, K_ie_mean, K_ie_std, K_ii_mean, K_ii_std):

    N = len(groups)
    N_exc = int(np.sum(groups == 0))
    N_inh = int(np.sum(groups == 1))
    K = np.zeros((N, N))

    # Pre-compute the interaction strengths for each pair of units
    for i in range(N):
        for j in range(N):
            if not i == j:
                if groups[i] == 0 and groups[j] == 0:
                    K[i, j] = np.random.normal(K_ee_mean, K_ee_std) / N_exc
                elif groups[i] == 1 and groups[j] == 0:
                    K[i, j] = np.random.normal(K_ei_mean, K_ei_std) / N_exc
                elif groups[i] == 0 and groups[j] == 1:
                    K[i, j] = -np.random.normal(K_ie_mean, K_ie_std) / N_inh
                elif groups[i] == 1 and groups[j] == 1:
                    K[i, j] = -np.random.normal(K_ii_mean, K_ii_std) / N_inh

    return K

