def binned_mean_error(x, y, edges, err_type='stderr', ddof=1, min_n=5):
    """
    edges: ビン境界（np.arange(start, stop+bin_w, bin_w)）
    err_type: 'std' か 'stderr'
    ddof=1 なら不偏標準偏差
    min_n: ビン内の最小サンプル数（未満は NaN）
    """
    x = np.asarray(x).ravel()
    y = np.asarray(y).ravel()
    m = ~np.isnan(x) & ~np.isnan(y)
    x, y = x[m], y[m]

    centers = (edges[:-1] + edges[1:]) / 2
    means = np.full(centers.shape, np.nan)
    errs  = np.full(centers.shape, np.nan)
    ns    = np.zeros(centers.shape, dtype=int)

    for k in range(len(centers)):
        sel = (x >= edges[k]) & (x < edges[k+1])
        ns[k] = sel.sum()
        if ns[k] >= min_n:
            mu = np.nanmean(y[sel])
            sd = np.nanstd(y[sel], ddof=ddof)
            means[k] = mu
            errs[k]  = sd if err_type=='std' else sd / np.sqrt(ns[k])
    return centers, means, errs, ns

